#!/usr/bin/env python3
"""
Canonical data-integrity audit. Reads the snapshots the pipeline already
produces and reports what is deterministic, what is ambiguous and what needs
a human decision. It changes nothing and relaxes nothing: every gate the
publisher enforces is re-checked here, never weakened.

    python3 scripts/paperdoll/audit.py
        -> docs/data-audit/best-bottles-canonical-data-audit.md
        -> data/paper-doll/audit-matrix.json

Inputs (all generated by the pipeline, all committed):
    convex-snapshot.json      products + groups + duplicate list
    component-snapshot.json   component edges + fitment rules
    plates-snapshot.json      the live index + its integrity sweeps
    xref.json                 the SKU <-> PSD join with its match kinds
    selection.json            one chosen source per (stem, cap state)
    inventory.json            every source file with a reason code
    tokens.json               the SKU vocabulary
    kit-audit.json            per-SKU layer facts
    alias-map.json            approved aliases (the ONLY match-time rewrite)
    alias-candidates.json     near-misses awaiting review
"""
from __future__ import annotations

import json
import re
import time
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
DATA = REPO / "data" / "paper-doll"
DOCS = REPO / "docs" / "data-audit"

COMPONENT_FAMILIES = {"Cap/Closure", "Sprayer", "Lotion Pump", "Dropper", "Roll-On Cap", "Reducer", "Overcap", "Roller Ball"}
# the four family ids that shipped before the grammar existed
LEGACY_ALIASES = {
    "diva-46-clear": "diva-46ml-clear-18-415",
    "diva-46-frosted": "diva-46ml-frosted-18-415",
    "cylinder-50ml-clear": "cylinder-50ml-clear-18-415",
    "cylinder-9ml-17-415": "cylinder-9ml-<glass>-17-415",
}
# 8-425 is a real neck standard, so the prefix is 1-2 digits; "18415" and "18-415"
# are the same thread spelled two ways, and both appear in component SKUs
THREAD_RE = re.compile(r"(?<!\d)(\d{1,2})-?(\d{3})(?!\d)")


def load(name):
    return json.loads((DATA / name).read_text())


def slug(value) -> str:
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", str(value).lower())).strip("-")


def family_id(product: dict, group: dict | None) -> tuple[str | None, str | None]:
    """The implemented grammar, recomputed here from product fields only."""
    g = group or {}
    family = g.get("family") or product.get("family")
    if product.get("category") == "Component" or family in COMPONENT_FAMILIES:
        neck = g.get("neckThreadSize") or product.get("neckThreadSize")
        if not family or not neck:
            return None, "missing:" + ",".join(n for n, v in (("family", family), ("neck", neck)) if not v)
        return f"{slug(family)}-{slug(neck)}", None
    capacity = g.get("capacityMl") if g.get("capacityMl") is not None else product.get("capacityMl")
    color = g.get("color") or product.get("color") or "mixed"
    neck = g.get("neckThreadSize") or product.get("neckThreadSize")
    missing = [n for n, v in (("family", family), ("capacityMl", capacity), ("neck", neck)) if v in (None, "")]
    if missing:
        return None, "missing:" + ",".join(missing)
    cap = f"{capacity:g}" if isinstance(capacity, (int, float)) else str(capacity)
    return f"{slug(family)}-{cap}ml-{slug(color)}-{slug(neck)}", None


def normalise_thread(value) -> str | None:
    m = THREAD_RE.search(str(value or ""))
    return f"{m.group(1)}-{m.group(2)}" if m else None


