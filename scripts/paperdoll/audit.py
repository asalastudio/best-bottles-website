def audit_identity(snap, xref):
    """§1 — one row per website SKU: is it unique, and what does it resolve to?"""
    groups = {g["_id"]: g for g in snap["groups"]}
    by_sku = defaultdict(list)
    for p in snap["products"]:
        by_sku[(p.get("websiteSku") or "").strip()].append(p)
    xref_by_sku = {r["websiteSku"]: r for r in xref["products"] if r["websiteSku"]}

    rows = []
    duplicates = []
    for sku, docs in sorted(by_sku.items()):
        if not sku:
            continue
        fids = []
        for d in docs:
            fid, reason = family_id(d, groups.get(d.get("productGroupId")))
            fids.append((fid, reason))
        state = "unique" if len(docs) == 1 else "duplicate"
        rows.append({
            "websiteSku": sku, "documents": len(docs), "uniquenessState": state,
            "graceSkus": sorted({d.get("graceSku") for d in docs if d.get("graceSku")}),
            "groupSlugs": sorted({(groups.get(d.get("productGroupId")) or {}).get("slug") for d in docs} - {None}),
            "familyIds": sorted({f for f, _ in fids if f}),
            "familyIdReasons": sorted({r for _, r in fids if r}),
            "matchKind": xref_by_sku.get(sku, {}).get("matchKind"),
            "publishable": xref_by_sku.get(sku, {}).get("publishable", False),
        })
        if len(docs) > 1:
            # classify WHY there is more than one document
            grace = {d.get("graceSku") for d in docs}
            group_ids = {d.get("productGroupId") for d in docs}
            fid_set = {f for f, _ in fids if f}
            names = {(d.get("itemName") or "")[:80] for d in docs}
            if len(grace) == 1 and len(group_ids) == 1:
                kind, action = "IDENTICAL_RECORD", "merge: same grace SKU, same group — one document should remain"
                confidence = "high"
            elif len(grace) > 1 and len(group_ids) == 1:
                kind, action = "DISTINCT_PRODUCTS_SHARING_A_WEBSITE_SKU", "assign a distinct website SKU to each product, or retire the surplus"
                confidence = "high"
            elif len(group_ids) > 1 and len(fid_set) > 1:
                kind, action = "SAME_SKU_IN_TWO_FAMILIES", "decide which family owns the SKU; the other document is misfiled or a different product"
                confidence = "high"
            else:
                kind, action = "SAME_SKU_DIFFERENT_GROUP", "confirm which product group is correct"
                confidence = "medium"
            duplicates.append({
                "websiteSku": sku, "kind": kind, "documents": len(docs),
                "documentIds": [d.get("_id") for d in docs],
                "graceSkus": sorted(g for g in grace if g),
                "groupSlugs": sorted({(groups.get(gid) or {}).get("slug") for gid in group_ids} - {None}),
                "familyIds": sorted(fid_set),
                "itemNames": sorted(n for n in names if n),
                "fields": {
                    "category": sorted({d.get("category") for d in docs if d.get("category")}),
                    "capacityMl": sorted({d.get("capacityMl") for d in docs if d.get("capacityMl") is not None}),
                    "color": sorted({d.get("color") for d in docs if d.get("color")}),
                    "neckThreadSize": sorted({d.get("neckThreadSize") for d in docs if d.get("neckThreadSize")}),
                    "applicator": sorted({d.get("applicator") for d in docs if d.get("applicator")}),
                },
                "recommendedResolution": action,
                "confidence": confidence,
                "evidence": "convex-snapshot.json — products sharing one websiteSku",
                "publishingBlocked": True,
            })
    return rows, duplicates


def audit_families(snap):
    """§2 — recompute familyId and look for collisions and lost necks."""
    groups = {g["_id"]: g for g in snap["groups"]}
    members = defaultdict(list)
    missing_neck = []
    for p in snap["products"]:
        g = groups.get(p.get("productGroupId"))
        fid, reason = family_id(p, g)
        if fid:
            members[fid].append((p, g))
        elif reason and "neck" in reason:
            missing_neck.append({"websiteSku": p.get("websiteSku"), "graceSku": p.get("graceSku"),
                                 "family": (g or {}).get("family") or p.get("family"),
                                 "groupSlug": (g or {}).get("slug"), "reason": reason})
    collisions = []
    for fid, entries in sorted(members.items()):
        necks = {(g or {}).get("neckThreadSize") or p.get("neckThreadSize") for p, g in entries}
        necks = {n for n in necks if n}
        if len(necks) > 1:
            collisions.append({"familyId": fid, "issue": "FAMILY_ID_COLLISION", "necks": sorted(necks),
                               "skus": sorted({p.get("websiteSku") for p, _ in entries})[:12],
                               "evidence": "two neck finishes recomputed to one familyId"})
    # family/capacity/colour combinations that legitimately span several necks:
    # these MUST stay separate, so they are the collision risk worth naming
    spans = defaultdict(set)
    for fid in members:
        parts = fid.rsplit("-", 2)
        if len(parts) == 3:
            spans[parts[0]].add(parts[1] + "-" + parts[2])
    multi_neck = {k: sorted(v) for k, v in spans.items() if len(v) > 1}
    return members, collisions, missing_neck, multi_neck


def audit_compatibility(comp, snap):
    """§6 — neck is first-order: a component whose thread differs from the bottle's is invalid."""
    invalid, unverified = [], []
    edges = 0
    by_thread_pairs = Counter()
    for p in comp["products"]:
        bottle_thread = normalise_thread(p.get("neckThreadSize"))
        for csku in p["componentSkus"]:
            edges += 1
            comp_thread = normalise_thread(csku)
            if comp_thread is None:
                unverified.append({"websiteSku": p["websiteSku"], "component": csku,
                                   "bottleNeck": p.get("neckThreadSize"),
                                   "issue": "COMPATIBILITY_UNVERIFIED",
                                   "reason": "component SKU carries no thread designation"})
            elif bottle_thread is None:
                unverified.append({"websiteSku": p["websiteSku"], "component": csku,
                                   "bottleNeck": p.get("neckThreadSize"),
                                   "issue": "COMPATIBILITY_UNVERIFIED",
                                   "reason": "product has no neck thread size"})
            elif comp_thread != bottle_thread:
                invalid.append({"websiteSku": p["websiteSku"], "component": csku,
                                "bottleNeck": bottle_thread, "componentNeck": comp_thread,
                                "issue": "COMPATIBILITY_INVALID",
                                "reason": f"{comp_thread} component declared on a {bottle_thread} bottle"})
                by_thread_pairs[(bottle_thread, comp_thread)] += 1
    return {"edges": edges, "invalid": invalid, "unverified": unverified, "invalidPairs": by_thread_pairs}


def audit_shared_descriptors(snap):
    """One physical part registered under several component ids? Group by descriptor stem
    (the id minus its trailing -NN) and show the item names, which is the evidence that
    decides it. Nothing is merged here: the suffix sometimes encodes a real physical
    difference (a dropper's glass stem length) and sometimes only a finish."""
    stem = lambda g: re.sub(r"-\d{2}$", "", g)
    groups = defaultdict(list)
    for p in snap["products"]:
        if p.get("category") == "Component" and p.get("graceSku"):
            groups[stem(p["graceSku"])].append(p)
    out = []
    for key, members in sorted(groups.items()):
        if len(members) < 2:
            continue
        names = {(m.get("itemName") or "").strip() for m in members}
        out.append({
            "descriptor": key,
            "componentIds": sorted(m["graceSku"] for m in members),
            "websiteSkus": sorted(m.get("websiteSku") or "?" for m in members),
            "itemNames": sorted(n for n in names if n),
            "identicalNames": len(names) == 1,
            "verdict": "SAME_DESCRIPTION_DIFFERENT_IDS" if len(names) == 1 else "DESCRIPTIONS_DIFFER",
        })
    return out


def audit_reuse(comp, snap, tokens):
    """§11 — one physical component, many SKUs. Count how far each is already shared."""
    groups = {g["_id"]: g for g in snap["groups"]}
    prod_by_sku = {(p.get("websiteSku") or "").strip(): p for p in snap["products"]}
    usage = defaultdict(lambda: {"skus": set(), "families": set(), "necks": set()})
    for p in comp["products"]:
        sku = p["websiteSku"]
        base = prod_by_sku.get(sku)
        fid = family_id(base, groups.get(base.get("productGroupId")))[0] if base else None
        for csku in p["componentSkus"]:
            u = usage[csku]
            u["skus"].add(sku)
            if fid:
                u["families"].add(fid)
            neck = normalise_thread(csku)
            if neck:
                u["necks"].add(neck)
    rows = [{"component": c, "skus": len(u["skus"]), "families": len(u["families"]),
             "necks": sorted(u["necks"]), "exampleSkus": sorted(u["skus"])[:4]}
            for c, u in usage.items()]
    rows.sort(key=lambda r: -r["skus"])
    return rows


def audit_plates(plates_snap, snap, xref):
    """§9 — one plate row per canonical SKU, and every field present."""
    rows = plates_snap["plates"]
    by_sku = Counter(r["sku"] for r in rows)
    conflicts = [{"sku": s, "rows": n, "issue": "PLATE_ROW_CONFLICT"} for s, n in by_sku.items() if n > 1]
    prod_grace = {}
    for p in snap["products"]:
        sku = (p.get("websiteSku") or "").strip()
        if sku:
            prod_grace.setdefault(sku, set()).add(p.get("graceSku"))
    field_issues = []
    for r in rows:
        if not r.get("image"):
            field_issues.append({"sku": r["sku"], "issue": "MISSING_FRONT"})
        if r.get("graceSku") and r["sku"] in prod_grace and r["graceSku"] not in prod_grace[r["sku"]]:
            field_issues.append({"sku": r["sku"], "issue": "GRACE_SKU_MISMATCH",
                                 "plate": r["graceSku"], "catalogue": sorted(x for x in prod_grace[r["sku"]] if x)})
        if not r.get("familyId"):
            field_issues.append({"sku": r["sku"], "issue": "MISSING_FAMILY_ID"})
    return {"rows": len(rows), "conflicts": conflicts, "fieldIssues": field_issues,
            "sweep": plates_snap["plateIntegrity"], "kitSweep": plates_snap["kitIntegrity"]}


def audit_tokens(tokens, members):
    """§7 — one token, one meaning; one meaning, one token."""
    ambiguous_bodies = {b: v for b, v in tokens["bodies"].items() if v.get("ambiguous")}
    # a canonical finish reached by several spellings is fine; two canonical finishes
    # sharing a spelling would not be
    spelling_owner = defaultdict(set)
    for label, f in tokens["finishes"].items():
        for spelling in f["spellings"]:
            spelling_owner[spelling].add(label)
    collisions = {s: sorted(v) for s, v in spelling_owner.items() if len(v) > 1}
    unknown_family = {b: v for b, v in tokens["bodies"].items()
                      if v.get("familyId") and v["familyId"] not in members}
    return {"ambiguousBodies": ambiguous_bodies, "spellingCollisions": collisions,
            "bodiesWithoutFamily": [b for b, v in tokens["bodies"].items() if not v.get("familyId")],
            "bodiesPointingAtUnknownFamily": unknown_family,
            "unparsed": tokens["unparsed"], "reviewedAt": tokens.get("reviewedAt")}


def audit_assets(inventory, selection):
    """§8 — every file classified, every exclusion reasoned, no photograph collapsed."""
    files = inventory["files"]
    unclassified = [f for f in files if not f.get("role") and not f.get("junkReason")]
    junk = Counter(f["junkReason"] for f in files if f.get("junkReason"))
    roles = Counter(f["role"] for f in files if f.get("role"))
    multi_location = 0
    for entry in selection["stems"].values():
        for state in entry["states"].values():
            if len(state.get("locations", [])) > 1:
                multi_location += 1
    thumbs_or_views_chosen = []
    for key, entry in selection["stems"].items():
        for state, rec in entry["states"].items():
            path = (rec.get("chosenPath") or "").lower()
            if "thumbnail" in path or "thumbail" in path:
                thumbs_or_views_chosen.append({"stem": key, "state": state, "path": rec.get("chosenPath")})
    return {"files": len(files), "unclassified": len(unclassified), "junk": dict(junk), "roles": dict(roles),
            "conflicts": selection.get("conflicts", []), "multiLocationAssets": multi_location,
            "thumbnailsChosenAsFront": thumbs_or_views_chosen,
            "hiresSetAside": len(selection.get("hiresSetAside", []))}


def main():
    started = time.time()
    snap = load("convex-snapshot.json")
    comp = load("component-snapshot.json")
    plates_snap = load("plates-snapshot.json")
    xref = load("xref.json")
    selection = load("selection.json")
    inventory = load("inventory.json")
    tokens = load("tokens.json")
    kit_audit = load("kit-audit.json")
    aliases = load("alias-map.json")
    candidates = load("alias-candidates.json")["candidates"]
    # are the approved aliases doing any work? an alias is needed only when its SKU does
    # not already match a PSD stem exactly
    catalogue_skus = {(p.get("websiteSku") or "").strip() for p in snap["products"]} - {""}
    all_stems = set()
    for entry in selection["stems"].values():
        all_stems.update(entry["stems"])
    alias_health = {
        "entries": len(aliases),
        "valueIsCatalogueSku": sum(1 for v in aliases.values() if v in catalogue_skus),
        "needed": sum(1 for v in aliases.values() if v in catalogue_skus and v not in all_stems),
        "redundant": sum(1 for v in aliases.values() if v in catalogue_skus and v in all_stems),
        "stale": sum(1 for k, v in aliases.items() if k not in all_stems and v not in catalogue_skus),
    }

    identity_rows, duplicates = audit_identity(snap, xref)
    members, collisions, missing_neck, multi_neck = audit_families(snap)
    compat = audit_compatibility(comp, snap)
    reuse = audit_reuse(comp, snap, tokens)
    plate_audit = audit_plates(plates_snap, snap, xref)
    token_audit = audit_tokens(tokens, members)
    asset_audit = audit_assets(inventory, selection)
    shared_descriptors = audit_shared_descriptors(snap)

    kinds = Counter(r["matchKind"] for r in xref["products"])
    publishable = [r for r in xref["products"] if r["publishable"]]
    # the gate, re-derived here rather than trusted
    gate_violations = [r["websiteSku"] for r in publishable
                       if r["matchKind"] not in ("exact", "alias") or r["convexDuplicate"] or r["blockReasons"]]

    no_psd = [r for r in xref["products"] if r["matchKind"] == "no-psd"]
    no_psd_class = Counter()
    for r in no_psd:
        if r["category"] in ("Packaging", "Accessory", "Tool"):
            no_psd_class["non-bottle product"] += 1
        elif r["convexDuplicate"]:
            no_psd_class["duplicate SKU"] += 1
        elif r["familyIdReason"]:
            no_psd_class["unsupported family (no neck)"] += 1
        else:
            no_psd_class["photography genuinely missing"] += 1

    matrix = {
        "generatedAt": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "note": "audit view over existing ids; not a production schema",
        "sources": {"convexSnapshot": snap["generatedAt"], "plates": plates_snap["generatedAt"], "xref": xref["generatedAt"]},
        "bySku": {},
        "byComponent": {},
    }
    # the closure assembly a SKU spells, and the kit slots it opens, straight from the
    # reviewed vocabulary — a label, never a source of identity
    import sys as _sys
    _sys.path.insert(0, str(HERE))
    from build_tokens import parse_sku as _parse_sku
    closure_meta = tokens["closures"]

    plate_by_sku = {r["sku"]: r for r in plates_snap["plates"]}
    comp_by_sku = {p["websiteSku"]: p for p in comp["products"]}
    kit_by_sku = {r["websiteSku"]: r for r in kit_audit["results"]}
    for r in xref["products"]:
        sku = r["websiteSku"]
        if not sku:
            continue
        plate = plate_by_sku.get(sku)
        matrix["bySku"][sku] = {
            "graceSku": r["graceSku"], "familyId": r["familyId"], "body": None, "neck": None,
            "matchKind": r["matchKind"], "publishable": r["publishable"], "blockReasons": r["blockReasons"],
            "closureAssembly": (lambda parsed: {
                "token": parsed["closure"],
                "label": closure_meta.get(parsed["closure"], {}).get("label"),
                "slots": closure_meta.get(parsed["closure"], {}).get("slots", []),
                "applicator": closure_meta.get(parsed["closure"], {}).get("applicator"),
            } if parsed["closure"] else None)(_parse_sku(sku)),
            "physicalComponents": comp_by_sku.get(sku, {}).get("componentSkus", []),
            "plate": {"image": plate["image"], "capOff": plate.get("imageCapOff"), "revision": plate["revision"]} if plate else None,
            "kit": {"completeness": kit_by_sku[sku]["completeness"]} if sku in kit_by_sku else None,
        }
    body_of = {}
    for body, meta in tokens["bodies"].items():
        if meta.get("familyId"):
            body_of[meta["familyId"]] = body
    for sku, row in matrix["bySku"].items():
        if row["familyId"]:
            row["body"] = body_of.get(row["familyId"])
            row["neck"] = "-".join(row["familyId"].rsplit("-", 2)[-2:])
    for r in reuse:
        matrix["byComponent"][r["component"]] = {"skuCount": r["skus"], "familyCount": r["families"],
                                                 "necks": r["necks"], "exampleSkus": r["exampleSkus"]}
    (DATA / "audit-matrix.json").write_text(json.dumps(matrix, indent=1))

    human_review = []
    for d in duplicates:
        human_review.append({"item": f"duplicate SKU {d['websiteSku']}", "decision": d["recommendedResolution"], "kind": d["kind"], "confidence": d["confidence"]})
    if candidates:
        human_review.append({"item": f"{len(candidates)} alias candidates", "decision": "promote into alias-map.json or reject; they cannot publish as near-misses", "kind": "ALIAS_REVIEW", "confidence": "high"})
    if not token_audit["reviewedAt"]:
        human_review.append({"item": "tokens.json reviewedAt is unset", "decision": "review the vocabulary and set reviewedAt; --dist publishing is blocked until then", "kind": "TOKEN_REVIEW", "confidence": "high"})
    for c in asset_audit["conflicts"]:
        human_review.append({"item": f"SAME_STEM_DIFFERENT_PHOTOGRAPH {c['stem']} [{c['state']}]", "decision": "choose which photograph is canonical, or rename one stem", "kind": "SELECTION_CONFLICT", "confidence": "high"})
    for c in collisions:
        human_review.append({"item": f"FAMILY_ID_COLLISION {c['familyId']}", "decision": "separate the necks; never drop the neck to resolve", "kind": "FAMILY_COLLISION", "confidence": "high"})
    for d in shared_descriptors:
        if d["identicalNames"]:
            human_review.append({"item": f"component descriptor {d['descriptor']} has {len(d['componentIds'])} ids with one description",
                                 "decision": "confirm whether these are one physical part (share geometry) or genuinely different (give them distinguishing descriptions)",
                                 "kind": "COMPONENT_DESCRIPTOR_AMBIGUOUS", "confidence": "medium"})

    out = {"duplicates": duplicates, "collisions": collisions, "missingNeck": missing_neck, "multiNeck": multi_neck,
           "compat": {k: (v if k != "invalidPairs" else {f"{a}->{b}": n for (a, b), n in v.items()}) for k, v in compat.items()},
           "tokens": token_audit, "assets": asset_audit, "plates": plate_audit,
           "sharedComponentDescriptors": shared_descriptors, "humanReview": human_review}
    (DATA / "audit-findings.json").write_text(json.dumps(out, indent=1, default=str))

    render_report(snap, xref, kinds, publishable, gate_violations, identity_rows, duplicates, members,
                  collisions, missing_neck, multi_neck, compat, reuse, plate_audit, token_audit,
                  asset_audit, kit_audit, aliases, candidates, no_psd_class, human_review, started, alias_health,
                  shared_descriptors)


def render_report(snap, xref, kinds, publishable, gate_violations, identity_rows, duplicates, members,
                  collisions, missing_neck, multi_neck, compat, reuse, plate_audit, token_audit,
                  asset_audit, kit_audit, aliases, candidates, no_psd_class, human_review, started, alias_health,
                  shared_descriptors):
    DOCS.mkdir(parents=True, exist_ok=True)
    L = []
    a = L.append
    a("# Best Bottles — canonical data integrity audit")
    a("")
    a(f"Generated {time.strftime('%Y-%m-%d %H:%M')} by `scripts/paperdoll/audit.py` from the committed pipeline snapshots.")
    a("This audit reads; it changes nothing and relaxes no gate. Every number below is recomputed from")
    a("`data/paper-doll/*.json` and the live Convex index, not copied from an earlier report.")
    a("")
    a("## Executive summary")
    a("")
    a("| measure | count |")
    a("|---|---:|")
