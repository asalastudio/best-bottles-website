"""Seat every 60/100 ml Elegant closure on its shoulder, and draw the PSD dip tube of each fitment.

Run after build-60-100-kits.mts (master glass) and psd-tubes-60-100.py (the regenerated tubes).

Glass axis: tassel kits stand their glass right of centre (glassSizing.axisPct) so the hose and tassel
   stay on the stage. Frosted droppers draw their seated pipette diffused through the glass.
0. Reducers. The 100 ml reducer kits get the 60 ml kits' reviewed 18-415 reducer (insert seated, full
   plug in EXPLODED), scaled by px/mm about the neck datum, so their pages offer cap off and exploded.

1. Shoulder seat. The register placed the closures for the earlier bodies; on the masters the
   frosted collars and caps sank 15-18 px into the glass and the 100 ml bulb collars 8-12 px.
   Each closure (sprayer, pump, dropper fitment, overcap, cap) moves vertically so its collar
   bottom, measured in its own alpha within the neck column, sits SEAT_GAP px below the first row
   at or under the shoulder (the first row under the neck wider than 1.3 x the neck) where the
   glass is as wide as the collar: the shoulder is rounded, so a wide collar rests lower. A
   sprayer's or pump's overcap moves with its head instead, keeping the register's registration of
   the head seen through (or covered by) it. A dropper's pipette moves
   with its fitment; the reducer plug stays in the neck.
2. Dip tubes (Jordan, 3 Nov 2026): the tubes in the Elegant 60 and 100 ml PSDs are the right ones.
   Each size has one per fitment type: the fine-mist sprayer's (pump body and tube), the lotion
   pump's (clear cylinder and thicker tube) and the bulb atomizer's (plain tube), regenerated by
   psd-tubes-60-100.py and placed by the PSD's own bottle-to-tube geometry: the box in fractions
   of the neck-top-to-foot height from the neck top and the glass axis. Every kit of a size and
   fitment type shares that one image. They multiply into the glass (blendMode), so the white
   core reads as translucent; frosted kits draw them in EXPLODED only, travelling with the fitment.

Usage: python3 scripts/elegant-masters/universal-dip-tube-60-100.py
"""
import hashlib, io, json, os, re
import numpy as np
from PIL import Image

KITS = "public/local-kits/elegant60-100-masters-2026-11-03/kits.json"
TUBES = "public/local-kits/elegant60-100-masters-2026-11-03/tubes/tubes.json"
STAGE_MARGIN = 3               # % of the stage width kept clear beside a tassel assembly
SEAT_GAP = 1                    # collar bottom this many px under the shoulder line: resting on it
CLOSURES = ("sprayer", "pump", "fitment", "overcap", "cap")

_images, _alpha = {}, {}


def image(url):
    if url not in _images:
        data = open("public" + url, "rb").read() if url.startswith("/") else __import__("urllib.request").request.urlopen(url, timeout=60).read()
        _images[url] = Image.open(io.BytesIO(data)).convert("RGBA")
    return _images[url]


def alpha(part):
    """The part's alpha at its drawn size, as (mask, x, y) in stage px."""
    b = part["box"]; key = (part["image"]["url"], round(b["width"], 2), round(b["height"], 2))
    if key not in _alpha:
        im = image(part["image"]["url"]).getchannel("A").resize((max(1, round(b["width"])), max(1, round(b["height"]))), Image.BILINEAR)
        _alpha[key] = np.asarray(im) > 60
    return _alpha[key], b["x"], b["y"]


def shoulder(kit):
    m, x, y = alpha(next(p for p in kit["parts"] if p["slot"] == "body"))
    w = m.sum(1); top = int(np.argmax(w > 0))
    neck = float(np.median(w[top + 15:top + 60]))
    r = top + 20
    while w[r] <= neck * 1.3:
        r += 1
    return y + r, neck, lambda stage_y: w[int(round(stage_y - y))]   # the glass's width at a stage row


def collar(part, axis, neck):
    """Collar bottom, centre and width in stage px: the lowest row at least the neck's width in the neck column."""
    m, x, y = alpha(part)
    lo, hi = max(0, round(axis - x - neck)), min(m.shape[1], round(axis - x + neck))
    rows = np.where(m[:, lo:hi].sum(1) >= neck * 0.95)[0]
    if not len(rows):
        return None, None, None
    r = int(rows.max()); c = round(axis - x)
    run = m[r]; a = c
    while a > 0 and run[a - 1]: a -= 1
    b = c
    while b < len(run) - 1 and run[b + 1]: b += 1                  # the collar's own run through the axis
    return y + r + 1, x + (a + b + 1) / 2, b - a + 1


def shift(part, dy):
    for p in (part, part.get("detached")):        # the parked cover travels with its seated overcap
        if p:
            p["box"] = {**p["box"], "y": round(p["box"]["y"] + dy, 3)}
            p["bounds"] = {**p["bounds"], "top": round(p["bounds"]["top"] + dy, 3), "bottom": round(p["bounds"]["bottom"] + dy, 3)}


DROPPERS = "/Volumes/Achive/Client Work/Nemat-International/BB-PSD-Files-Master/20. Caps/29. 18-415 Droppers"


def complete_dropper(finish):
    """The whole 18-415 dropper photographed on its own (Drp18-415<finish>.psd), with its collar measured."""
    # The Sunburst regeneration of the photograph (regenerate-droppers.py): its geometry, real glass pipette.
    img = Image.open(f"public/local-kits/elegant60-100-masters-2026-11-03/droppers/Drp18-415{finish}-r2.png").convert("RGBA")
    a = np.asarray(img)[..., 3] > 128; w = a.sum(1)
    rows_ = np.where(w >= w.max() * 0.92)[0]                 # the collar: the widest band
    bottom = int(rows_.max()) + 1; xs = np.where(a[bottom - 3])[0]
    out = "public/local-kits/elegant60-100-masters-2026-11-03/droppers"
    os.makedirs(out, exist_ok=True)
    for old in os.listdir(out):
        if old.startswith(f"Drp18-415{finish}-") and not old.endswith("-r2.png"):
            os.remove(f"{out}/{old}")
    halves = {}
    for half, crop in (("head", (0, 0, img.width, bottom)), ("pipette", (0, bottom, img.width, img.height))):
        part = img.crop(crop)
        buf = io.BytesIO(); part.save(buf, "PNG", optimize=True); data = buf.getvalue()
        sha = hashlib.sha256(data).hexdigest()
        path = f"{out}/Drp18-415{finish}-{half}-{sha[:12]}.png"; open(path, "wb").write(data)
        halves[half] = {"url": "/" + path.removeprefix("public/"), "key": "", "sha256": sha, "bytes": len(data), "width": part.width, "height": part.height}
    return {"image": {"width": img.width, "height": img.height}, **halves,
            "collarWidth": int(xs.max() - xs.min() + 1), "collarCentre": (xs.min() + xs.max() + 1) / 2, "collarBottom": bottom,
            "source": f"20. Caps/29. 18-415 Droppers/Drp18-415{finish}.psd (complete dropper)"}


def main():
    kits = json.load(open(KITS))
    rows = kits["rows"]

    # 0. The 100 ml reducer kits came from the register as glass and cap only, so the product page could only
    #    show them capped (it offers SIDECAR and EXPLODED for a reducer when the kit has one). The 18-415
    #    reducer is one component across sizes: draw the 60 ml kits' reviewed insert (seated) and plug
    #    (EXPLODED), scaled by px/mm about the neck datum, and lift the cap a unit above it.
    template = rows["GBElg60RdcrPnkLthr"]
    t_ppm = template["anchors"]["pxPerMm"]; t_d = template["register"]["datum"]
    t_reducers = [p for p in template["parts"] if p["slot"] == "reducer"]
    for sku, kit in rows.items():
        if "Rdcr" not in sku or any(p["slot"] == "reducer" for p in kit["parts"]):
            continue
        k = kit["anchors"]["pxPerMm"] / t_ppm; d = kit["register"]["datum"]
        added = []
        for src in t_reducers:
            r = json.loads(json.dumps(src)); b = src["box"]
            box = {"x": round(d["axisX"] + (b["x"] - t_d["axisX"]) * k, 3), "y": round(d["seatY"] + (b["y"] - t_d["seatY"]) * k, 3),
                   "width": round(b["width"] * k, 3), "height": round(b["height"] * k, 3)}
            r.update({"box": box, "bounds": {"left": box["x"], "top": box["y"], "right": round(box["x"] + box["width"], 3), "bottom": round(box["y"] + box["height"], 3)},
                      "source": f"{template['sku']} reducer, scaled {k:.4f} (18-415, {t_ppm} -> {kit['anchors']['pxPerMm']} px/mm)"})
            added.append(r)
        body = [p for p in kit["parts"] if p["slot"] == "body"]
        rest = [p for p in kit["parts"] if p["slot"] != "body"]
        for p in rest:
            p["explodeIndex"] = max(p.get("explodeIndex", 1), 2)
        kit["parts"] = body + added + rest
        for z, p in enumerate(kit["parts"]):
            p["zOrder"] = z
        kit["register"] = {**kit["register"], "componentIds": sorted(set(kit["register"].get("componentIds", [])) | {added[0]["componentId"]})}

    # 1. Seat every closure on its own glass's shoulder.
    for sku, kit in rows.items():
        sh, neck, glass_width = shoulder(kit)
        axis = kit["register"]["datum"]["axisX"]
        kit["glassShoulderY"] = int(sh)
        moved = {}
        # Overcaps last: a sprayer's or pump's overcap image is registered to that head (a clear one shows
        # it through the cover), so it moves with the head; seated on its own it printed the pump twice.
        for part in sorted((p for p in kit["parts"] if p["slot"] in CLOSURES), key=lambda p: p["slot"] == "overcap"):
            head = next((p for p in kit["parts"] if p["slot"] in ("sprayer", "pump")), None)
            if part["slot"] == "overcap" and head is not None and head["slot"] in moved:
                shift(part, moved[head["slot"]])
                part["seatWith"] = head["slot"]
                part.pop("seatBottomY", None); part.pop("collarWidth", None)
                continue
            bottom, cx, width = collar(part, axis, neck)
            if bottom is None:
                continue
            # The Elegant shoulder rounds over ~14 px: a collar rests where the glass is as wide as it is,
            # or a wide collar's corners (the white treatment pump's band) hang over the ground.
            rest = sh
            while glass_width(rest) < width * 0.97:
                rest += 1
            dy = rest + SEAT_GAP - bottom
            shift(part, dy)
            moved[part["slot"]] = dy
            part["seatBottomY"] = int(rest + SEAT_GAP)
            part["collarWidth"] = int(width)
            if part["slot"] == "fitment":
                for pip in (p for p in kit["parts"] if p["slot"] == "pipette"):
                    shift(pip, dy)

    # 1a. Glass axis. A vintage bulb's hose and tassel reach far left of the glass (to the floor beside it at
    #     60 ml): stand the glass axis right of centre, by the scaler's own scale, so the whole assembly is on
    #     the stage with STAGE_MARGIN% to spare (product page and builder share the frame).
    for sku, kit in rows.items():
        if "AnSpTsl" not in sku:
            continue
        sp = next(p for p in kit["parts"] if p["slot"] == "sprayer")
        body = next(p for p in kit["parts"] if p["slot"] == "body")["bounds"]
        m, x, y = alpha(sp)
        left = x + int(np.argmax(m.any(0)))
        g = kit["glassSizing"]
        pct = g["heightPct"] / 100 * kit["canvas"]["height"] / (body["bottom"] - g["landmarkY"]) / kit["canvas"]["width"] * 100   # % of width per px
        axis = kit["anchors"]["axisX"]
        g["axisPct"] = round(min(100 - STAGE_MARGIN - (body["right"] - axis) * pct, max(50, STAGE_MARGIN + (axis - left) * pct)), 2)

    # 1b. A clear lotion overcap's register layer is the capped photograph: the cover with the pump inside.
    #     Drawn over the pump layer in CAP ON it printed the pump twice (Jordan, 3 Nov 2026). Seat the empty
    #     cover the stage already parks beside the glass (detached-overcaps.ts) where the photographed cover
    #     stands: centred, at the cover's width, its top on the photograph's top; the one pump shows through.
    for sku, kit in rows.items():
        for part in kit["parts"]:
            look = part.get("detached") or {}
            if part["slot"] != "overcap" or not look.get("image", {}).get("url", "").endswith("-clear-overcap.webp"):
                continue
            m, x, y = alpha(part)
            top = y + int(np.argmax(m.any(1)))
            b = {**look["box"], "y": round(float(top), 3)}
            part.update({"image": {**part["image"], **look["image"], "key": "", "sha256": "", "bytes": 0}, "image2x": None, "mask": None,
                         "box": b, "bounds": {"left": b["x"], "top": b["y"], "right": round(b["x"] + b["width"], 3), "bottom": round(b["y"] + b["height"], 3)},
                         "derivation": "empty-cover-seated",
                         # The cover is drawn opaque light grey for the bone ground; multiplied, it is clear
                         # plastic over the pump head, the head showing through as in the photograph.
                         "blendMode": "multiply"})
            part["detached"] = {**look, "box": dict(b), "bounds": dict(part["bounds"])}

    # 1c. Droppers (Jordan, 3 Nov 2026): no silhouette through frosted glass; the pipette stays hidden under it,
    #     and EXPLODED lifts the complete dropper (bulb, collar and pipette) from the master library's 18-415
    #     dropper photographs, one per finish, regenerated with real glass pipettes (regenerate-droppers.py), scaled and placed so its collar is the seated collar. The stage
    #     offers EXPLODED for a dropper kit that carries it (stage.ts separableDropper).
    # One scale for every finish: the three photographs share one rig, so their own collar measurements (which
    # differ by a few px) drew the droppers at different sizes (Jordan, 3 Nov 2026). Silver sets it.
    # The register's seated collars differ too (silver 181 px, gold and copper ~220), so the stage size is the
    # median seated collar of the size's dropper kits.
    droppers = {"Sl": complete_dropper("Sl")}
    seated_collars = sorted(next(p for p in k["parts"] if p["slot"] == "fitment")["collarWidth"]
                            for s, k in rows.items() if re.match(r"GBElg(?:Frst)?60Drp(Cu|Gl|Sl)$", s))
    collar_px = seated_collars[len(seated_collars) // 2]
    for sku, kit in rows.items():
        m = re.match(r"GBElg(?:Frst)?60Drp(Cu|Gl|Sl)$", sku)
        if not m:
            continue
        if m.group(1) not in droppers:
            droppers[m.group(1)] = complete_dropper(m.group(1))
        d = droppers[m.group(1)]
        fit = next(p for p in kit["parts"] if p["slot"] == "fitment")
        pipette = next(p for p in kit["parts"] if p["slot"] == "pipette")
        body = next(p for p in kit["parts"] if p["slot"] == "body")
        if kit["register"]["glass"] == "Frosted":
            pipette["zOrder"] = body["zOrder"] - 0.5          # under the frosted glass: hidden while seated
        for p in (fit, pipette):
            p["views"] = ["sidecar", "capon"]
        axis = kit["register"]["datum"]["axisX"]
        s_ = collar_px / droppers["Sl"]["collarWidth"]
        box = {"x": round(axis - d["collarCentre"] * s_, 3), "y": round(fit["seatBottomY"] - d["collarBottom"] * s_, 3),
               "width": round(d["image"]["width"] * s_, 3), "height": round(d["image"]["height"] * s_, 3)}
        # Two layers of one unit: bulb and collar as photographed, the glass pipette multiplied (the photograph
        # bakes the clear glass near white, which vanishes on the light stage; multiplied, its walls show).
        for half, top_ in (("head", 0), ("pipette", d["collarBottom"])):
            img = d[half]
            b_ = {**box, "y": round(box["y"] + top_ * s_, 3), "height": round(img["height"] * s_, 3)}
            whole = {**fit, "image": dict(img), "image2x": None, "mask": None, "views": ["exploded"], "derivation": "psd-layer",
                     "source": d["source"], "box": b_, "zOrder": fit["zOrder"] + (0.1 if half == "head" else 0.05),
                     "bounds": {"left": b_["x"], "top": b_["y"], "right": round(b_["x"] + b_["width"], 3), "bottom": round(b_["y"] + b_["height"], 3)}}
            for k_ in ("seatBottomY", "collarWidth", "blendMode"):
                whole.pop(k_, None)
            if half == "pipette":
                whole["blendMode"] = "multiply"
            kit["parts"].append(whole)

    # 2. The PSD tube of each size and fitment type.
    tubes = json.load(open(TUBES))
    shared = {}
    for sku, kit in rows.items():
        fit = next((p for p in kit["parts"] if p["slot"] in ("sprayer", "pump")), None)
        old = [p for p in kit["parts"] if p["slot"] == "diptube"]
        if fit is None or not old:
            continue
        seated = next(p for p in old if p.get("views") != ["exploded"])
        kind = "lotion" if fit["slot"] == "pump" else "spray" if "-spray." in seated["image"]["url"] else "atomizer"
        size = kit["register"]["bodyId"].split("-")[1].removesuffix("ml")
        t = tubes[f"{size}-{kind}"]
        d = kit["register"]["datum"]; H = d["baselineY"] - d["seatY"]
        box = {"x": round(d["axisX"] + t["left"] * H, 3), "y": round(d["seatY"] + t["top"] * H, 3),
               "width": round(t["width"] * H, 3), "height": round(t["height"] * H, 3)}
        sha = hashlib.sha256(open("public" + t["file"], "rb").read()).hexdigest()
        tube = {**seated, "image": {"url": t["file"], "key": "", "sha256": sha, "bytes": os.path.getsize("public" + t["file"]),
                                    "width": t["pixels"][0], "height": t["pixels"][1]},
                "image2x": None, "mask": None, "derivation": f"psd-tube:{kind}", "blendMode": "multiply", "box": box,
                "bounds": {"left": box["x"], "top": box["y"], "right": round(box["x"] + box["width"], 3), "bottom": round(box["y"] + box["height"], 3)},
                "explodeIndex": fit.get("explodeIndex", 1),
                # EXPLODED keeps a head and its tube one unit by component (src/lib/products/exploded-stack.ts):
                # the tube takes its own head's, or it is laid out apart from the pump.
                "componentId": fit.get("componentId")}
        tube.pop("views", None)
        if kit["register"]["glass"] == "Frosted":
            tube["views"] = ["exploded"]
        rest = [p for p in kit["parts"] if p["slot"] != "diptube"]
        kit["parts"] = [p for p in rest if p["slot"] == "body"] + [tube] + [p for p in rest if p["slot"] != "body"]
        for z, p in enumerate(kit["parts"]):
            p["zOrder"] = z
        shared.setdefault(f"{size}-{kind}", []).append(sku)
    kits.pop("universalPumpBodies", None); kits.pop("universalDipTubeFrom", None)
    kits["universalDipTube"] = {key: {"url": tubes[key]["file"], "psd": tubes[key]["psd"], "skus": sorted(skus)} for key, skus in shared.items()}
    kits["version"] = hashlib.sha256(json.dumps(kits["rows"], sort_keys=True).encode()).hexdigest()[:12]
    open(KITS, "w").write(json.dumps(kits, indent=1) + "\n")
    for key, skus in shared.items():
        print(key, "tube shared by", len(skus), "kits")
    print("version", kits["version"])


if __name__ == "__main__":
    main()
